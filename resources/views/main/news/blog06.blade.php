                            <p>Pentru majoritatea salariaților, munca de la distanță s-a transformat într-un stil de viață
                                datorită beneficiilor cu care vine la pachet, iar flexibilitatea pe care o presupune a
                                făcut posibilă inclusiv desfășurarea activității profesionale din străinătate. </br>
                                În afara românilor care au ales destinații exotice pentru a-și stabili noul birou,
                                sunt și angajați străini care au ales să revină în țările de origine pe durata pandemiei,
                                continuând însă munca pentru companiile la care sunt salariați.</p>


                            <div class="blockquote">

                                <p>Multe reguli privind telemunca au fost puse în aplicare odată cu instituirea stării de
                                    urgență și menținute pe toată perioada stării de alertă, însă odată ce această perioadă
                                    va trece,
                                    companiile trebuie să ia în considerare implementarea unei politici clare privind
                                    telemunca, dacă se dorește păstrarea acestui mod de lucru.
                                    Implementarea unei astfel de politici este întărită de faptul că, după doi ani în care
                                    s-a muncit preponderent de la distanță, păstrarea acestui mod de lucru nu mai
                                    reprezintă,
                                    pentru angajat, doar o favoare sau o concesie pentru situații excepționale, ci și, în
                                    unele cazuri, o condiție pentru a rămâne angajat în cadrul unei companiii</p>

                                <small>a explicat <cite>Ioana Dragu, Tax Senior Consultant Soter & Partners.</cite></small>

                            </div>

                            <h4>Cât costă munca remote din străinătate pentru angajator</h4>

                            <p>În situația în care angajatorul permite salariaților munca de la distanță în străinătate,
                                compania trebuie să cunoască implicațiile care pot decurge din această schimbare,
                                în special în ceea ce privește impozitul pe venit, contribuțiile sociale, riscul de sediu
                                permanent, securitatea în muncă, obligațiile de declarare și raportare în străinătate,
                                precum și posibilele formalități de imigrare. <br>


                            <div class="blockquote">

                                <p>În ceea ce privește impozitul pe venit, atunci când activitatea este desfășurată în
                                    străinătate,
                                    trebuie analizat în primul rând dacă România și țara gazdă au încheiat o convenție
                                    pentru evitarea dublei impuneri.
                                    Având în vedere că România a încheiat aproximativ 90 de convenții în acest scop, există,
                                    în majoritatea cazurilor, un cadru legal pentru a stabili care stat are,
                                    în final, drept de impunere. În cazul țărilor cu care România nu are încheiată o
                                    convenție în acest sens, precum Tanzania sau Mauritius,
                                    angajatorul trebuie să aibă în vedere că există riscul unei duble impuneri, atât în
                                    România, cât și în celălalt stat</p>

                                <small>a explicat <cite>Andrei Popescu, Tax Manager Soter & Partners.</cite></small>

                            </div>

                            <p>În sfera contribuțiilor sociale, dacă ne raportăm la nivelul Uniunii Europene, acestea nu pot
                                fi plătite în două sau mai multe state membre simultan,
                                potrivit Regulamentului (CE) nr. 883/2004 privind coordonarea sistemelor de securitate
                                socială. </p>

                            <div class="blockquote">

                                <p>Angajatorul trebuie să efectueze o analiză separată pentru a stabili dacă, în funcție de
                                    situația fiecărui salariat aflat în telemuncă în străinătate,
                                    contribuțiile sociale ajung să fie datorate în alt stat decât cel de origine. Un angajat
                                    poate rămâne, în anumite condiții, asigurat în România în ciuda
                                    desfășurării activității în alt stat membru al Uniunii Europene. Pentru a nu datora
                                    contribuții sociale în statul în care se prestează munca în regim de telemuncă,
                                    angajatorul poate solicita formularul portabil A1 pentru angajații săi, în anumite
                                    condiții specifice. În lipsa unui formular A1, există riscul ca angajatul să datoreze
                                    contribuții
                                    sociale în statul în care acesta prestează munca, risc care poate atrage mai departe
                                    obligația companiei de a se înregistra în scop de contribuții sociale în statul
                                    respectiv.
                                    Pe de altă parte, în cazul în care activitatea se desfășoară într-un stat din afara
                                    Uniunii Europene, trebuie verificat dacă există o convenție bilaterală de securitate
                                    socială
                                    încheiată între România și statul respectiv. În cazul statelor cu care România nu a
                                    încheiat un acord bilateral, pot fi datorate contribuții sociale atât în România, cât și
                                    în celălalt stat</p>

                                <small>a adăugat <cite>Ioana Dragu, Tax Senior Consultant Soter & Partners.</cite></small>

                            </div>


                            <h4>Telemunca în afara țării și riscul generării unui sediu permanent pentru angajator</h4>

                            <p>Munca la distanță din străinătate poate genera, în anumite condiții, obligații suplimentare
                                pentru angajator, un alt aspect important de avut în vedere fiind riscul
                                generării unui sediu permanent în străinătate.</p>



                            <div class="blockquote">

                                <p>Prezența unui angajat în afara țării poate genera un risc de sediu permanent pentru
                                    angajator. Deși activitatea de telemuncă în sine nu generează automat un sediu permanent
                                    pentru companie,
                                    este necesară evaluarea acestui risc, ținând cont de activitatea prestată de salariat și
                                    de reglementările din țara în care se desfășoară activitatea. Riscul generării unui
                                    sediu permanent poate crește,
                                    în schimb, în cazul în care compania solicită în mod expres angajatului să utilizeze o
                                    locație specifică pentru a desfășura activitate. De asemenea, riscul de sediu permanent
                                    poate apărea și atunci când
                                    o persoană încheie contracte în numele companiei într-un alt stat decât statul de
                                    rezidență al companiei</p>

                                <small>a explicat <cite>Andrei Popescu, Tax Manager Soter & Partners.</cite></small>

                            </div>

                            <p>Implementarea unei politici de telemuncă de către angajator necesită o analiză amănunțită a
                                tuturor acestor implicații pentru a putea oferi salariaților un cadru
                                sigur și predictibil în ceea ce privește munca la distanță. Acest lucru este important cu
                                atât mai mult cu cât, un studiu realizat de Randstad Workmonitor și publicat în 2021 arată
                                că peste 80% dintre angajații români își doresc în continuare mai multă flexibilitate la
                                job, ceea ce indică faptul că munca de la distanță devine un trend de care angajatorii
                                trebuie să țină seama.</p>

