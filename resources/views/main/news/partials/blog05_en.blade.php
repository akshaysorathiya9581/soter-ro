<p>For most companies, the accounting and fiscal year is ending, and December is the perfect moment to look back at the past 12 months from a financial perspective and to pinpoint future investment opportunities or optimisation measures.</p>

<p>A rigorous review of financial performance and accounting reality is even more important considering that, according to a Valoria study on Romanian businesses in 2021, 21% of respondents say their profit will be more than 20% higher this year.</p>

<p>Moreover, 22% of companies expect their turnover to increase by 5%–10% in 2021, and 18% estimate growth of over 20%, compared with only 12% at the beginning of the year.</p>

<div class="blockquote">
    <p>This year, under Article 11(2) of the Fiscal Procedure Code, all tax obligations related to November, as well as those due on 25 December, must be settled by 21 December. That shorter timeframe pressures companies when closing their accounting and tax books and also tightens their cash flow, since they have less time to make payments.</p>
    <p>“In a constantly changing legislative environment, companies need seasoned accounting and tax professionals who can prevent or minimise potential deficiencies identified by the authorities.”</p>
    <small>explained <cite>Mihaela Rișco-Martin, Accounting Partner, Soter &amp; Partners</cite></small>
</div>

<h4>Tax deficiencies detected by ANAF in 2021</h4>

<p>According to ANAF’s latest report on tax inspections carried out in 2021, the most common issues include:</p>
<ol>
    <li>incorrect calculation of the taxable result;</li>
    <li>failure to register for VAT purposes after exceeding the small-business exemption threshold (300,000 lei);</li>
    <li>non-compliance by taxable persons declared inactive who continue doing business but do not pay taxes and social contributions;</li>
    <li>errors in completing the VAT return;</li>
    <li>breaching the rules for deducting VAT—claiming input tax for acquisitions unrelated to taxable operations or lacking supporting documents.</li>
</ol>

<p>Romanian companies still have work to do to keep up with their tax obligations and avoid penalties, especially since studies show that 44% of business leaders expect profitability to return to pre-pandemic levels in 2022.</p>

<h4>The major tax novelty of 2022</h4>

<p>Financial results and the way companies close their books will be key indicators when setting goals for 2022. The numbers highlight progress made during the year and signal areas that need improvement.</p>

<div class="blockquote">
    <p>“At year end it’s best to review every balance and every figure, and to perform both quantitative and qualitative inventory counts so that the accounts accurately reflect reality. There are plenty of decisions that can lead to tax optimisation: recording provisions for old, unpaid receivables; reclassifying advances paid for which invoices were not received or closing them with VAT adjustments; using any unused tax credits via sponsorships; closing partially delivered transactions that will not be completed; reinvesting profit.”</p>
    <p>“The better prepared the accountant, the longer the list of closing and optimisation actions.”</p>
    <small>explained <cite>Mihaela Rișco-Martin, Accounting Partner, Soter &amp; Partners</cite></small>
</div>

<p>A key fiscal novelty for 2022 is the option to set up a profit tax group. Assessing 2020–2021 can be the right time to analyse this decision, since a consolidated group can improve overall tax efficiency. Joining is optional, but once the option is exercised, it must be maintained for at least five years.</p>

