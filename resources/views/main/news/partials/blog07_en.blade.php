<p>The flexibility of working hours and the possibility of remote work brought by the pandemic reshaped how employees see their jobs and pushed many to reassess their priorities.</p>

<p>Experts expect the global wave of resignations—“the Great Resignation”—to continue, so employers must offer new incentives: tailored benefit packages, personal development opportunities and continuous professional training. Recent studies show that 70% of employees aged 35‑54 would choose better perks over a salary raise.</p>

<h4>Employer-initiated training – legal obligations</h4>

<p>Professional training helps employees sharpen their skills or acquire new ones for promotions and better performance. When the employer initiates training, it is important to classify the time spent as working time or not.</p>

<div class="blockquote">
    <p>“The Labour Code does not explicitly state whether employer-initiated training counts as working or rest time; it only mentions that if the training happens during regular hours, employees keep their salary rights, seniority and social contribution record. Directive 2003/88/EC also lacks clarity, but in case C‑909/19 the Court of Justice of the EU ruled on 28 October 2021 that such periods are ‘working time’.”</p>
    <small>explained <cite>Luminița Obaciu, Senior Payroll Partner, Soter &amp; Partners</cite></small>
</div>

<div class="blockquote">
    <p>“Article 13 of Directive (EU) 2019/1152 on transparent and predictable working conditions clearly states that employer-initiated training counts as working time. The directive must be transposed into national law by 1 August 2022.”</p>
    <small>she added <cite>Luminița Obaciu, Senior Payroll Partner, Soter &amp; Partners</cite></small>
</div>

<h4>Time off when courses take place on weekends</h4>

<div class="blockquote">
    <p>“If training sessions are scheduled on Saturday and Sunday, the work schedule must ensure that employees still receive 48 consecutive hours of weekly rest. When training takes place after the regular workday, the employer must respect the rule that after 12 hours of work employees are entitled to 24 hours of rest, as well as the maximum working-time limits.”</p>
    <small>added <cite>Luminița Obaciu, Senior Payroll Partner, Soter &amp; Partners</cite></small>
</div>

<p>Access to professional training, combined with enhanced benefit packages and flexible schedules, are key when employees choose a new job and are effective tools for retaining talent. According to a recent BestJobs survey, more than 41% of employees expect their companies to support their professional development in 2022.</p>

