<p>The idea of digital nomads is not new, but the pandemic turned remote work into an easily accessible alternative. The Inter-American Development Bank estimates there could be one billion digital nomads by 2050.</p>

<p>This new type of tourist-worker spends longer periods in one community rather than taking short vacations. As of 17 January 2022, Romania joined the list of countries that grant temporary residence permits to digital nomads.</p>

<p>The law requires a valid employment contract, proof of tax payments, and a monthly income at least three times the Romanian gross average salary for the previous six months as well as for the entire visa period. Applicants must also conduct their work remotely using information and communication technology.</p>

<p>Such regulations can help revive local jobs in hospitality and cultural sectors while boosting tax revenues for the state.</p>

