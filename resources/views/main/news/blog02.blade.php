                            <p>Integrarea persoanelor cu dizabilități pe piața muncii reprezintă un proces esențial pentru
                                dezvoltarea profesională și perfecționarea abilităților și calificărilor acestei categorii
                                sociale,
                                dar și pentru garantarea egalității de șanse, sporirea incluziunii sociale și asigurarea
                                unui trai decent pe termen lung. </p>


                            <p>La nivel european, doar în 2019, persoanele cu dizabilități aveau cu 24,4% mai puține șanse
                                de a fi angajate decât cele fără dizabilități și doar 50,8% dintre acestea aveau un loc de
                                muncă.
                                În România, potrivit datelor Autorităţii Naţionale pentru Drepturile Persoanelor cu
                                Dizabilităţi, Copii şi Adopţii (ANDPDCA),
                                la 30 iunie 2021, număr total de persoane cu dizabilități era de 861, 016, numărul fiind în
                                creștere de la an la an. Dintre acestea, 52,87% sunt persoane cu vârsta cuprinsă între 18-64
                                ani</p>

                            <p>Persoanelor cu dizabilități ar trebui să le fie garantat dreptul fundamental la muncă și
                                angajare asemenea persoanelor fără dizabilități,
                                drept prevăzut în articolul 27 al Convenției ONU privind drepturile persoanelor cu handicap
                                (CDPH).</p>

                            <p>Pentru a încuraja companiile să angajeze persoane cu dizabilități, statul român acordă
                                firmelor care încadrează în muncă astfel de persoane
                                o sumă în cuantum de 2.250 lei pentru fiecare angajat cu dizabilități pe o perioadă de 12
                                luni, cu obligația menținerii raporturilor de serviciu cel puțin 18 luni.
                            </p>

                            <p>Cu toate acestea, însă, potrivit unei diagnoze a situației persoanelor cu dizabilități din
                                România, realizată de Autoritatea Națională pentru Drepturile Persoanelor cu Dizabilități,
                                Copii și Adopții (ANDPDCA) cu sprijinul Băncii Mondiale în 2020, rata de ocupare a
                                persoanelor cu dizabilități din România este mult mai scăzută decât a persoanelor fără
                                dizabilități și sub media celorlalte țări ale Uniunii Europene. </p>


                            <p>În România, dacă 74% dintre persoanele între 20 și 64 de ani fără limitări sunt ocupate,
                                procentul este de doar 51% pentru persoanele cu unele limitări și scade dramatic la
                                persoanele cu limitări severe (doar 12% dintre acestea sunt ocupate), rămânând aproape
                                constantă în perioada 2010-2018 pentru cea din urmă categorie. </p>

                            <div class="blockquote">

                                <p>”Potrivit Legii nr. 448 din 2006 privind protecţia şi promovarea drepturilor persoanelor
                                    cu dizabilități, autorităţile şi instituţiile publice, persoanele juridice,
                                    publice sau private, care au cel puţin 50 de angajaţi, au obligaţia de a angaja persoane
                                    cu dizabilități într-un procent de cel puţin 4% din numărul total de angajaţi, </p>
                                <small>a explicat <cite> Luminița Obaciu, Senior Payroll Partner, Soter &
                                        Partners.</cite></small>

                            </div>

                            <p>Cu toate acestea, în 2018, unele dintre cele mai importante instituții de stat nu aveau nicio
                                persoană cu dizabilități angajată,
                                iar printre acestea se numără Ministerul Finanțelor, Ministerul Mediului, Ministerul
                                Energiei, Ministerul Culturii sau Ministerul Comunicațiilor.</p>


                            <div class="blockquote">

                                <p>În situația în care instituțiile de stat sau companiile private nu angajează persoane cu
                                    dizabilități, acestea trebuie să plătească către bugetul statului,
                                    lunar, o suma echivalentă cu salariul de bază minim brut înmulțit cu numărul de locuri
                                    de muncă neocupate de persoane cu dizabilități</p>

                                <small>a explicat <cite> Luminița Obaciu, Senior Payroll Partner, Soter &
                                        Partners.</cite></small>

                            </div>

                            <p>La încheierea unui contract de muncă cu o persoană cu dizabilități fie într-o instituție
                                publică, fie într-o instituție privată,
                                există anumite prevederi legale specifice din Codul Muncii, dar si cele reglementate de
                                Legea 448/2006 privind protecția și promovarea persoanelor cu handicap,
                                care trebuie avute în vedere și puse în aplicare, precum cele legate de perioada de probă,
                                perioada de concediu de odihnă, perioada de preaviz sau plata impozitului pe venit.</p>

                            <div class="blockquote">

                                <p>În situația angajării unei persoane cu dizabilități, este important să fie avute în
                                    vedere atât prevederile specifice din Codul Muncii,
                                    dar și cele reglementate de Legea 448/2006 privind protecția și promovarea acestora. Una
                                    dintre prevederile specifice se referă la perioada de
                                    probă ce poate fi stabilită la încheierea unui contract individual de muncă cu o
                                    persoană cu dizabilități. Analizând aspectele legislative referitoare la perioada de
                                    probă,
                                    observăm că prevederile din cele doua acte normative sunt contradictorii, Codul Muncii
                                    reglementând o perioadă de probă de maximum 30 de zile calendaristice,
                                    în timp ce Legea 448/2006 stabilește cel puțin 45 de zile lucrătoare. În această
                                    situație, prevederile Legii 448/2006 sunt cele aplicabile, nu cele ale Codului Muncii.
                                    Astfel, perioada de probă în cazul persoanelor cu dizabilități ce se încadrează în baza
                                    unui contract pe perioada nedeterminată este de minimum 45 de zile lucrătoare
                                    și nu de maximum 30 de zile calendaristice.
                                    În ceea ce privește concediul de odihnă, persoanele cu dizabilități beneficiază de o
                                    perioadă suplimentară de cel puțin 3 zile lucrătoare. Și durata preavizului în cazul
                                    concedierii este diferită.
                                    Persoana cu dizabilități beneficiază de un preaviz plătit, de minimum 30 de zile
                                    lucrătoare, acordat la desfacerea contractului individual de muncă din iniţiativa
                                    angajatorului pentru motive
                                    neimputabile acestuia, spre deosebire de restul salariaților pentru care perioada de
                                    preaviz reglementată de Codul Muncii este de cel puțin 20 de zile lucrătoare.
                                    De asemenea, o prevedere importantă din Codul Fiscal este cea cu privire la tratamentul
                                    fiscal al veniturilor din salarii realizate de persoanele cu dizabilități și
                                    face referire la faptul că persoanele cu handicap mediu și accentuat sunt scutite de
                                    plata impozitului pe venit </p>
                                <small>a explicat <cite> Luminița Obaciu, Senior Payroll Partner, Soter &
                                        Partners.</cite></small>

                            </div>

                            <p>În acest moment, persoanele cu dizabilități sunt o resursă de muncă puțin folosită în România
                                așa cum arată datele statistice, chiar dacă din punct de vedere legal
                                instituțiile statului și companiile private cu cel puțin 50 de angajați au obligativitatea
                                angajării acestora. </p>


                            <p>Pentru a face progrese în această sferă, atât mediul privat, cât și statul trebuie să
                                respecte prevederile legale, contribuind la o integrare mai facilă
                                a persoanelor cu dizabilități în câmpul muncii, care pot în acest fel să-și perfecționeze
                                competențele profesionale și să își asigure un trai decent. </p>
