                            <h4>Drepturi salariale și de asigurări sociale stabilite în funcție de orele lucrate, nu de zile
                                în contextul lucrului hibrid</h4>


                            <p>Pentru a reflecta cât mai aproape de adevăr flexibilitatea în stabilirea orelor de lucru și
                                având în vedere actualele condiții de muncă și tendința tot mai
                                mare a unui program inegal în rândul salariaților care lucrează la distanță, specialiștii
                                atrag atenția asupra faptului că autoritățile ar trebui să aibă în vedere
                                anumite modificări în legislația muncii, ce vor atrage după sine schimbări importante în
                                stabilirea drepturilor salariale și de asigurări sociale ale angajaților.</p>


                            <div class="blockquote">

                                <p>Particularitățile apărute în practică, precum programul de lucru inegal, reducerea
                                    programului de lucru sau situațiile în care salariații lucrează cu timp parțial în
                                    mai puține zile lucrătoare și cu program diferit de la o zi la alta determină
                                    necesitatea unei analize atente a legislației aferente,
                                    ținând cont de faptul că anumite drepturi se determină în funcție de zile, iar altele în
                                    funcție de ore</p>
                                <small>a explicat <cite> Luminița Obaciu, Payroll Partner, Soter & Partners.</cite></small>

                            </div>

                            <p>Spre exemplu, un salariat care este încadrat în baza unui contract individual de muncă cu
                                timp parțial de 1 oră/zi și 5 ore/săptămână va lucra câte o oră în fiecare zi lucrătoare din
                                lună, având astfel un stagiu lunar de cotizare egal cu numărul de zile lucrătoare din lună.
                                Pe de altă parte, în situația în care un salariat este încadrat în baza unui contract
                                individual de muncă cu timp parțial de 5 ore/săptămână repartizate într-o singură
                                zi/săptămână,
                                acesta va lucra o singură zi/săptămână, având un stagiu lunar de cotizare egal cu 4 sau 5
                                zile maximum/lună. În ambele situații, cei doi salariați au
                                același volum de muncă în termeni de ore lucrate, însă acestea din urmă sunt distribuite în
                                mod diferit.</p>

                            <p>Potrivit specialiștilor, cele două scenarii de mai sus sunt din ce în ce mai întâlnite pe
                                piața muncii, iar una dintre consecințele importante se reflectă asupra
                                stabilirii drepturile de asigurări sociale ale salariaților, unde se pot înregistra
                                diferențe majore. </p>

                            <div class="blockquote">

                                <p>Având in vedere că dreptul la concediu și indemnizația de concediu medical reglementată
                                    de OUG 158/2005 sunt condiționate de îndeplinirea stagiului de cotizare de 6 luni în
                                    ultimele 12 (cu anumite excepții),
                                    stagiul fiind calculat în funcție de numărul de zile lucrate și nu în funcție de numărul
                                    de ore lucrate, se poate observa că, deși salariatul prestează același
                                    volum de muncă în ambele situații, nivelul salarial și nivelul contribuțiilor sociale
                                    este același. În prima situație, salariatul poate îndeplini condiția privind
                                    stagiul de cotizare de 6 luni în ultimele 12, însă în cea de-a doua situație salariatul
                                    nu va putea îndeplini această condiție, astfel că nu va putea beneficia de concedii și
                                    indemnizații de concedii medicale. De asemenea, similar este și în cazul stagiului de
