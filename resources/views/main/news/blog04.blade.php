                            <p>Pandemia de COVID-19 a făcut ca munca la distanță să devină o opțiune din ce în ce mai
                                frecventă pentru angajați, iar programul clasic de opt ore să nu mai fie o constantă.</p>


                            <p>Lucrul în regim de telemuncă a oferit flexibilitate și posibilitatea gestionării individuale
                                a programului de lucru,
                                35% dintre angajați fiind de părere că posibilitatea de a lucra de acasă le oferă mai multă
                                liberate în utilizarea orelor de muncă. Cu toate acestea,
                                lucrul de la distanță a favorizat creșterea cu 14% a numărului de ore suplimentare în
                                ultimul an, potrivit unui studiu global realizat de Adecco,
                                aspect ce încurajează angajații să își distribuie orele de lucru/săptămână pentru o cât mai
                                bună organizare a timpului.</p>


                            <p>Cu toate acestea, deși lucrul de la distanță s-a dovedit a fi o modalitate eficientă și utilă
                                de continuare a activității profesionale,
                                mulți dintre salariați s-au aflat în situația de a lucra constant mai multe ore pe zi decât
                                cele prevăzute în contractul de muncă. </p>

                            <p>În acest context, programul de lucru tinde să devină unul inegal, iar în anumite situații
                                greu de gestionat,
                                având în vedere alternanța timpului de lucru cu timp personal în cadrul unei zile de lucru
                                în regim de telemuncă. </p>

                            <div class="blockquote">

                                <p>Perioada atipică pe care o traversăm din 2020 și până astăzi a determinat, pe de o parte,
                                    nevoia fluctuantă de forță de muncă,
                                    iar pe de altă parte nevoia salariaților de a avea o anumită autonomie în stabilirea
                                    programului de lucru.
                                    Astfel, se simte nevoia flexibilizării programului de lucru și dezvoltării legislației
                                    în acest context.
                                    Este clar că în multe sectoare de activitate vremea programului de muncă fix de 8 ore/zi
                                    a apus, programul inegal fiind din ce în ce mai des întâlnit în practică.
                                    Așadar, trebuie ținut seamă de faptul că tendința pe piața muncii este de a stabili
                                    programe flexibile, programe inegale de lucru, fapt ce
