            <h3>First courses organized by Soter</h3>

            <p align="justify">
                In 1993, The Ministry of Finance decides to change the accounting system enherited from communists and to
                implement the new accounting system, including a new chart of accounts, coppied from French.
                These being the purpose, the Finance Ministry, through the Advisory Accounting Board, approved the
                organizing specialized courses, trough these the old regime’s accountants  were supposed to be informed with
                capitalists models of evidence. This was an opportunity and Soter S.R.L. took the authorization to organize
                this kind of courses. In 1994, in the first couple of months of the year managed to organize – together with the Ministry of Finance’s lectors –
                some sessions of courses, from which were raised about 8.000.000 lei. The amount turned out to be very important for the economic life of the company,
                not as a value, but because for the first time, were created the premises to rent an office and to leave the sphere of “apartment firms”.
                Taking into account the currency value back then and also the rental value in a central area, the amount had to be sufficient for 6 months.
            </p>

