            <h4>11. Data transfers</h4>

            <p align="justify">11.1 All exports of data from within the European Economic Area (EEA) to non-European
                Economic Area countries (referred to in the GDPR as <q>third countries<q>)
                        are unlawful unless there is an appropriate <q>level of protection for the fundamental rights of the
                            data subjects<q>.</p>

            <p align="justify">11.2 The transfer of personal data outside of the EEA is prohibited unless one or more of the
                specified safeguards, or exceptions, apply:</br>

            <ul>
                <li>11.2.1 An adequacy decision The European Commission can and does assess third countries, a territory
                    and/or specific sectors
                    within third countries to assess whether there is an appropriate level of protection for the rights and
                    freedoms of natural persons. In these instances no authorisation is required.
                    Countries that are members of the European Economic Area (EEA) but not of the EU are accepted as having
                    met the conditions for an adequacy decision.
                    A list of countries that currently satisfy the adequacy requirements of the Commission are published in
                    the Official Journal of the European Union.
                    <br>
                    <strong><a
                            href="https://ec.europa.eu/info/law/law-topic/data-protection_en">https://ec.europa.eu/info/law/law-topic/data-protection_en</a></strong>
                </li>
                <li> 11.2.2 Privacy Shield <br>
                    If SOTER & PARTNERS wishes to transfer personal data from the EU to an organisation in the United States
                    it should check that the
                    organisation is signed up with the Privacy Shield framework at the U.S. Department of Commerce. The
                    obligation applying to companies under the Privacy Shield
                    are contained in the <q>Privacy Principles</q>. The US DOC is responsible for managing and administering
                    the Privacy Shield and ensuring that companies live up to their commitments.
                    In order to be able to certify, companies must have a privacy policy in line with the Privacy Principles
                    e.g. use, store and further transfer the personal data according to a strong
                    set of data protection rules and safeguards. The protection given to the personal data applies
                    regardless of whether the personal data is related to an EU resident or not.
                    Organisations must renew their <q>membership</q> to the Privacy Shield on an annual basis. If they do
                    not, they can no longer receive and use personal data from the EU under that framework.
                </li>
            </ul>

            <p align="justify"> Assessment of adequacy by the data controller <br>
                In making an assessment of adequacy, the Romania based exporting controller should take account of the
                following factors:<br>
            <ul>
                <li>the nature of the information being transferred;</li>
                <li>the country or territory of the origin, and final destination, of the information;</li>
                <li>how the information will be used and for how long;</li>
                <li>the laws and practices of the country of the transferee, including relevant codes of practice and
                    international obligations; </li>
            </ul>

