            <h4>5. Data protection principles</h4>


            <p align="justify">All processing of personal data must be conducted in accordance with the data protection
                principles as set out in Article 5 of the GDPR.
                SOTER & PARTNERS�s policies and procedures are designed to ensure compliance with the principles.</p>

            <p align="justify">5.1 Personal data must be processed lawfully, fairly and transparently</p>

            <p align="justify"><em>Lawful</em> - identify a lawful basis before you can process personal data. These are
                often referred to as the <q>conditions for processing<q>, for example consent.</p>

            <p align="justify"><em>Fairly</em> -in order for processing to be fair, the data controller has to make certain
                information available to the data subjects as practicable.
                This applies whether the personal data was obtained directly from the data subjects or from other sources.
            </p>

            <p align="justify">The GDPR has increased requirements about what information should be available to data
                subjects, which is covered in the <q>Transparency</q> requirement .</p>

            <p align="justify">Transparently- the GDPR includes rules on giving privacy information to data subjects in
                Articles 12, 13 and 14. These are detailed and specific,
                placing an emphasis on making privacy notices understandable and accessible. Information must be
                communicated to the data subject in an intelligible form using clear and plain language. </p>


            <p align="justify">SOTER & PARTNERS set out the Privacy Notice Procedure and the Privacy Notice regarding the
                processing of personal information. </p>

            <p align="justify">The specific information that must be provided to the data subject must, as a minimum,
                include:

            <ul>
                <li>5.1.1 the identity and the contact details of the controller and, if any, of the controller's
                    representative;</li>
                <li>5.1.2 the contact details of the Data Protection Officer;</li>
                <li>5.1.3 the purposes of the processing for which the personal data are intended as well as the legal basis
                    for the processing;</li>
                <li>5.1.4 the period for which the personal data will be stored;</li>
                <li>5.1.5 the existence of the rights to request access, rectification, erasure or to object to the
                    processing, and the conditions (or lack of)
                    relating to exercising these rights, such as whether the lawfulness of previous processing will be
                    affected;</li>
                <li>5.1.6 the categories of personal data concerned;</li>
                <li>5.1.7 the recipients or categories of recipients of the personal data, where applicable;</li>
                <li>5.1.8 where applicable, that the controller intends to transfer personal data to a recipient in a third
                    country and the level of protection afforded to the data;</li>
                <li>5.1.9 any further information necessary to guarantee fair processing.</li>

