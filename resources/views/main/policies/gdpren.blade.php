            <h4>7. Consent</h4>

            <p align="justify">7.1 SOTER & PARTNERS understands <q>consent </q> to mean that it has been explicitly and
                freely given, and a specific, informed and unambiguous indication of the data subject�s wishes that,
                by statement or by a clear affirmative action, signifies agreement to the processing of personal data
                relating to him or her. The data subject can withdraw their consent at any time.</p>

            <p align="justify">7.2 SOTER & PARTNERS understands <q>consent </q> to mean that the data subject has been fully
                informed of the intended processing and has signified their agreement, while in a fit state of mind
                to do so and without pressure being exerted upon them. Consent obtained under duress or on the basis of
                misleading information will not be a valid basis for processing. </p>

            <p align="justify">7.3 There must be some active communication between the parties to demonstrate active
                consent. Consent cannot be inferred from non-response to a communication.
                The Controller must be able to demonstrate that consent was obtained for the processing operation.</p>

            <p align="justify">7.4 For sensitive data, explicit written consent Consent Procedure of data subjects must be
                obtained unless an alternative legitimate basis for processing exists.</p>

            <p align="justify">7.5 In most instances, consent to process personal and sensitive data is obtained routinely
