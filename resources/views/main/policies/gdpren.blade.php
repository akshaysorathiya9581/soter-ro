            <h4>2. Data Protection Legislation </h4>
            <p align="justify">2.1 The General Data Protection Regulation 2016 replaces the EU Data Protection Directive of
                1995 and
                supersedes the laws of individual Member States that were developed in compliance with the Data Protection
                Directive 95/46/EC.
                Its purpose is to protect the <q>rights and freedoms</q> of natural persons (i.e. living individuals) and to
                ensure that personal data is not processed without their knowledge, and,
                wherever possible, that it is processed with their consent. </p>

            <p align="justify">2.2 Our Data protection policies are governed by EU data protection legislation and national
                data protection legislation in force.

            <h4>2.3 Definitions used by the organisation:</h4>

            <p align="justify"> Material scope - the GDPR applies to the processing of personal data wholly or partly by
                automated means (i.e. by computer)
                and to the processing other than by automated means of personal data (i.e. paper records) that form part of
                a filing system or are intended to form part of a filing system.</p>

            <p align="justify">Territorial scope - the GDPR will apply to all controllers that are established in the EU
                (European Union) who process the personal data of data subjects,
                in the context of that establishment. It will also apply to controllers outside of the EU that process
                personal data in order to offer goods and services, or monitor the behavior
                of data subjects who are resident in the EU.</p>

            <p align="justify">Establishment - the main establishment of the controller in the EU will be the place in which
                the controller makes the main
                decisions as to the purpose and means of its data processing activities. The main establishment of a
                processor in the EU will be its administrative centre.
                If a controller is based outside the EU,
                it will have to appoint a representative in the jurisdiction in which the controller operates to act on
                behalf of the controller and deal with supervisory authorities </p>

            <p align="justify">Personal data - any information relating to an identified or identifiable natural person
                ('data subject'); an identifiable
                natural person is one who can be identified, directly or indirectly, in particular by reference to an
                identifier such as a name, an identification number,
                location data, an online identifier or to one or more factors specific to the physical, physiological,
                genetic, mental, economic, cultural or social identity of that natural person.</p>

            <p align="justify">Special categories of personal data - personal data revealing racial or ethnic origin,
                political opinions,
                religious or philosophical beliefs, or trade-union membership, and the processing of genetic data,
                biometric data for the purpose of uniquely identifying a natural person, data concerning health or data
                concerning a natural person's sex life or sexual orientation. </p>

            <p align="justify">Data controller - the natural or legal person, public authority, agency or other body which,
                alone or jointly with others, determines the purposes and means of the processing of personal data; where
                the purposes and
                means of such processing are determined by Union or Member State law,
                the controller or the specific criteria for its nomination may be provided for by Union or Member State law.
            </p>

            <p align="justify">Data subject - any living individual who is the subject of personal data held by an
                organisation.</p>


            <p align="justify">Processing - any operation or set of operations which is performed on personal data or on
                sets of personal data,
                whether or not by automated means, such as collection, recording, organisation,
                structuring, storage, adaptation or alteration, retrieval, consultation, use, disclosure by transmission,
                dissemination or otherwise making available,
                alignment or combination, restriction, erasure or destruction. </p>

            <p align="justify">Personal data breach - a breach of security leading to the accidental, or unlawful,
                destruction, loss, alteration,
                unauthorised disclosure of, or access to, personal data transmitted, stored or otherwise processed.
                There is an obligation on the controller to report personal data breaches to the supervisory authority and
                where the breach is likely to
                adversely affect the personal data or privacy of the data subject.</p>

            <p align="justify">Data subject consent - means any freely given, specific, informed and unambiguous indication
                of the data subject's
                wishes by which he or she, by a statement or by a clear affirmative action, signifies agreement to the
                processing of personal data.</p>

            <p align="justify">Child - the GDPR defines a child as anyone under the age of 16 years old, although this may
                be lowered to 13 by Member State law.
                The processing of personal data of a child is only lawful if parental or custodian consent has been
                obtained.
                The controller shall make reasonable efforts to verify in such cases that consent is given or authorised by
                the holder of parental responsibility over the child.</p>

            <p align="justify">Third party - a natural or legal person, public authority, agency or body other than the data
                subject, controller,
                processor and persons who, under the direct authority of the controller or processor, are authorised to
                process personal data.</p>

            <p align="justify">Filing system - any structured set of personal data which are accessible according to
                specific criteria,
                whether centralised, decentralised or dispersed on a functional or geographical basis.</p>

