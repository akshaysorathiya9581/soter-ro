            <div class="hr-title center"><abbr>Agenda completă a evenimentului</abbr></div>

            <ul>
                <li><strong>I. TAXARE COMPANII</strong></li>
                <ul>
                    <li><strong><em>IMCA</em></strong></li>
                    <li>Aspecte de calcul – precizări noi în norme (ex: reduceri comerciale și credit fiscal).</li>
                    <li>Sponsorizări în context IMCA.</li>
                    <li>Credit fiscal pentru cercetare-dezvoltare în context IMCA.</li>
                    <li><strong><em>ICAS</em></strong></li>
                    <li>Aplicabilitate extinsă (petrol și gaze, comercianți de uleiuri minerale, cărbune, material lemnos).
                    </li>
                    <li>Extindere sferă 2025:</li>
                    <ul>
                        <li>Eliminarea plafonului de 50.000.000 euro.</li>
                        <li>Includerea prestatorilor de servicii specializate pentru extracție petrol și gaze (CAEN 0910).
                        </li>
                    </ul>
                </ul>

                <li><strong><em>Microîntreprinderi</em></strong></li>
                <ul>
                    <li>Reducerea plafonului la 250.000 euro în 2025.</li>
                    <li>Eliminarea condiției privind ponderea veniturilor din consultanță/management.</li>
                    <li>Noi precizări privind entitățile legate.</li>
                </ul>

                <li><strong><em>Alte prevederi privind impozitul pe profit</em></strong></li>
                <ul>
                    <li>Schimbarea formulei și a perioadei de reportare a pierderilor.</li>
                    <li>Formulă nouă pentru calculul costurilor excedentare de îndatorare.</li>
                    <li>Formular nou 101.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>II. IMPOZIT PE CONSTRUCȚII</strong></li>
                <ul>
                    <li>Impozit nou de 1% aplicat valorii construcțiilor (altele decât cele supuse impozitului pe clădiri).
                    </li>
                    <li>Cazuri speciale: amenajări ale spațiilor închiriate, clădiri cu scutiri locale (de ex. parcuri
                        industriale).</li>
                </ul>
            </ul>

            <ul>
                <li><strong>III. IMPOZIT PE DIVIDENDE</strong></li>
                <ul>
                    <li>Cotă majorată la 10% pentru dividende distribuite din 2025.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>IV. SALARII</strong></li>
                <ul>
                    <li>Eliminarea facilităților pentru IT, construcții, agricultură și industria alimentară.</li>
                    <li>Modificarea Codului Muncii prin Legea 283/2024.</li>
                    <li>Impactul modificării salariului minim.</li>
                    <li>Noutăți privind contribuția la fondul de handicap (solicitări de sprijin, definirea produselor
                        comercializabile).</li>
                </ul>
            </ul>

            <ul>
                <li><strong>V. TVA</strong></li>
                <ul>
                    <li>Modificări privind conținutul facturilor simplificate.</li>
                    <li>Ajustări pentru bunuri de capital.</li>
                    <li>Jurisprudență recentă a Curții Europene de Justiție.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VI. E-FACTURA &amp; E-TVA</strong></li>
                <ul>
                    <li>Noi faze de implementare în 2025 (B2C).</li>
                    <li>Precizări din ghidul codurilor E-Factura.</li>
                    <li>Notificări privind diferențe semnificative în E-Decont.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VII. E-TRANSPORT</strong></li>
                <ul>
                    <li>Obligații noi pentru 2025 (șoferi, transportatori, AEO).</li>
                    <li>Regim sancționatoriu actualizat (confiscări graduale, excepții pentru bunuri înregistrate).</li>
                    <li>Notificări privind diferențe semnificative în E-Decont.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VIII. PROCEDURĂ FISCALĂ</strong></li>
                <ul>
                    <li>Noi fapte de evaziune: creditarea firmei în anumite condiții, nereținerea la sursă etc.</li>
                </ul>
            </ul>
