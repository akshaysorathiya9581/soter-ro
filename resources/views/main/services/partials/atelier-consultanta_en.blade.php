    <div class="col-md-8 col-md-offset-2">
        <div class="col-md-12">
            <div class="hr-title center"><abbr>Full agenda</abbr></div>

            <ul>
                <li><strong>I. CORPORATE TAXATION</strong></li>
                <ul>
                    <li><strong><em>IMCA</em></strong></li>
                    <li>Calculation clarifications: updated guidance on commercial discounts and tax credits.</li>
                    <li>Sponsorship treatment under IMCA.</li>
                    <li>R&amp;D tax credit within IMCA.</li>
                    <li><strong><em>ICAS</em></strong></li>
                    <li>Extended scope beyond upstream oil &amp; gas (e.g., fuel distributors, coal, timber traders).</li>
                    <li>2025 expansion:</li>
                    <ul>
                        <li>Removal of the 50,000,000 EUR threshold.</li>
                        <li>Inclusion of specialized service providers for oil &amp; gas extraction (CAEN 0910).</li>
                    </ul>
                </ul>

                <li><strong><em>Micro-enterprises</em></strong></li>
                <ul>
                    <li>Threshold reduced to 250,000 EUR for 2025.</li>
                    <li>Removal of the consulting/management revenue cap.</li>
                    <li>Additional guidance for related entities.</li>
                </ul>

                <li><strong><em>Other corporate income tax rules</em></strong></li>
                <ul>
                    <li>New formula and period for loss carry-forward.</li>
                    <li>Updated formula for exceeding borrowing costs.</li>
                    <li>Revised Form 101.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>II. CONSTRUCTION TAX</strong></li>
                <ul>
                    <li>New 1% tax applied to the value of certain constructions (not subject to building tax).</li>
                    <li>Special cases: fitted-out rented spaces, tax treatment for buildings enjoying local exemptions (e.g.,
                        industrial parks).</li>
                </ul>
            </ul>

            <ul>
                <li><strong>III. DIVIDEND TAX</strong></li>
                <ul>
                    <li>Rate increased to 10% for dividends distributed starting 2025.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>IV. PAYROLL</strong></li>
                <ul>
                    <li>Removal of incentives for IT, construction, agriculture, and food industry employees.</li>
                    <li>Labour Code changes via Law 283/2024.</li>
                    <li>Impact of minimum wage adjustments.</li>
                    <li>Updates on disability fund contributions (support requests, definition of eligible products).</li>
                </ul>
            </ul>

            <ul>
                <li><strong>V. VAT</strong></li>
                <ul>
                    <li>Changes to simplified invoice content.</li>
                    <li>Adjustments for capital goods.</li>
                    <li>Recent ECJ case law.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VI. E-INVOICE &amp; E-VAT</strong></li>
                <ul>
                    <li>New rollout phases for 2025 (B2C coverage).</li>
                    <li>Useful clarifications from the e-Invoice code guide.</li>
                    <li>Notifications on significant discrepancies in e-Returns.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VII. E-TRANSPORT</strong></li>
                <ul>
                    <li>New obligations for drivers, transporters and AEO operators.</li>
                    <li>Updated penalties: gradual confiscation, exceptions for recorded goods.</li>
                    <li>Notifications on differences reported via e-Return.</li>
                </ul>
            </ul>

            <ul>
                <li><strong>VIII. PROCEDURAL TAX LAW</strong></li>
                <ul>
                    <li>New offences treated as tax evasion: specific shareholder loans, failure to withhold at source,
                        etc.</li>
                </ul>
            </ul>
        </div>

